package org.glassfish.main.test.app.mprestclient.webapp;

import jakarta.ws.rs.GET;
import jakarta.ws.rs.Path;
import jakarta.ws.rs.Produces;
import jakarta.ws.rs.core.MediaType;

import org.eclipse.microprofile.rest.client.inject.RegisterRestClient;

/**
 * The client interface has no class-level {@code @Path}: Jersey would otherwise also deploy it
 * as a root resource, ambiguous with {@link GreetingEndpoint}.
 */
@RegisterRestClient(configKey = "greeting")
public interface GreetingClient {

    @GET
    @Path("/greeting")
    @Produces(MediaType.TEXT_PLAIN)
    String greet();
}
